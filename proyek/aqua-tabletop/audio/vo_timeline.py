"""Lay the voice-over lines on the film clock and split each into subtitle cues (one line each, no wrapping).
Writes src/vo.js (LINES, VO cues, DUR) and vo/timeline.json. Reads vo/lines.json, the WAVs and vo/words.json (Whisper word times)."""
import json, os, re, soundfile as sf
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(ROOT, 'vo')
L = json.load(open(os.path.join(V, 'lines.json'))); W = json.load(open(os.path.join(V, 'words.json')))
START = [.5, 2.8, 6.65, 10.1, 11.85, 14.5, 20.2, 22.95, 28.65, 32.1, 37.1, 42.9, 46.1, 53.9, 60.9, 64.7, 71.9, 78.6, 83.0, 86.4]
DUR = 92.0
MAXC = 62

def chunks(text):
    """split at commas, then halve any piece that is still too long at the word nearest its middle"""
    if len(text) <= 66: return [text]
    parts = [p.strip() for p in re.split(r'(?<=,)\s+', text) if p.strip()]
    out = []
    for p in parts:
        stack = [p]
        while stack:
            s = stack.pop(0)
            if len(s) <= MAXC: out.append(s); continue
            ws = s.split(); best = min(range(1, len(ws)), key=lambda k: abs(len(' '.join(ws[:k])) - len(s) / 2))
            stack[:0] = [' '.join(ws[:best]), ' '.join(ws[best:])]
    # merge short pieces into a neighbour (the shorter one) while the cue still fits two lines
    m = out[:]
    while True:
        k = next((i for i, s in enumerate(m) if len(s) < 26 and len(m) > 1), None)
        if k is None: break
        cand = [j for j in (k - 1, k + 1) if 0 <= j < len(m) and len(m[j]) + 1 + len(m[k]) <= 82]
        if not cand: break
        j = min(cand, key=lambda j: len(m[j])); a, b = sorted((j, k))
        m[a:b + 1] = [m[a] + ' ' + m[b]]
    return m

lines, cues = [], []
for i, l in enumerate(L):
    d = sf.info(os.path.join(V, l['id'] + '.wav')).duration; t0 = START[i]; t1 = t0 + d
    lines.append({'id': l['id'], 't0': round(t0, 3), 't1': round(t1, 3), 'text': l['text']})
    cs = chunks(l['text']); words = W.get(l['id'], []); total = sum(len(c) for c in cs); acc = 0; prev = t0
    for k, c in enumerate(cs):
        acc += len(c)
        if k == len(cs) - 1: end = t1
        else:
            est = d * acc / total
            gaps = [w[1] for w in words]   # word start times: a cue ends where a word begins
            end = t0 + (min(gaps, key=lambda g: abs(g - est)) if gaps else est)
        cues.append({'t0': round(prev, 3), 't1': round(end, 3), 'zh': c, 'en': '', 'line': l['id']}); prev = end
js = '// Voice-over on the film clock (generated by audio/vo_timeline.py). LINES: spoken lines; VO: subtitle cues.\n'
wt = {l['id']: [[w[0], round(lines[i]['t0'] + w[1], 3), round(lines[i]['t0'] + w[2], 3)] for w in W.get(l['id'], [])] for i, l in enumerate(L)}
js += f'export const WT = ' + json.dumps(wt, ensure_ascii=False) + ';\n'
js += f'export const DUR = {DUR};\nexport const LINES = ' + json.dumps(lines, ensure_ascii=False) + ';\nexport const VO = ' + json.dumps(cues, ensure_ascii=False, indent=0) + ';\n'
open(os.path.join(ROOT, 'src/vo.js'), 'w').write(js)
json.dump({'dur': DUR, 'lines': lines, 'cues': cues}, open(os.path.join(V, 'timeline.json'), 'w'), ensure_ascii=False, indent=1)
for c in cues: print(f"{c['t0']:6.2f} {c['t1']:6.2f} {len(c['zh']):2d} {c['zh']}")
print('last line ends', lines[-1]['t1'])
